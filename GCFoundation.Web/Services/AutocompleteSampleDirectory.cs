using GCFoundation.Components.Models;
using GCFoundation.Web.Services.Interfaces;
using System.Globalization;
using System.Text;

namespace GCFoundation.Web.Services
{
    /// <summary>
    /// An in-memory directory of randomly generated, fictional people for the <c>fdcp-autocomplete</c> samples.
    /// The generator is seeded, so the same records are produced on every start and tests can rely on them.
    /// </summary>
    /// <remarks>
    /// This class also models what a real data source must enforce on the server, whatever the client sends:
    /// a minimum term length, a maximum page size and a limit on how deep a caller can page.
    /// </remarks>
    public sealed class AutocompleteSampleDirectory : IAutocompleteSampleDirectory
    {
        /// <summary>The number of records generated by default.</summary>
        public const int DefaultCount = 5000;

        /// <summary>The seed used by default.</summary>
        public const int DefaultSeed = 20251117;

        /// <summary>Terms shorter than this return no results.</summary>
        public const int MinTermLength = 2;

        /// <summary>The largest page a caller can request.</summary>
        public const int MaxPageSize = 100;

        /// <summary>The deepest offset a caller can page to.</summary>
        public const int MaxSkip = 5000;

        /// <summary>Terms longer than this are rejected.</summary>
        public const int MaxTermLength = 100;

        private static readonly string[] FirstNames =
        [
            "Marie", "Jean", "Zoé", "Liam", "Noah", "Chloé", "Amélie", "Omar", "Mei", "Aiyana",
            "Étienne", "Sophie", "Lucas", "Emma", "Olivier", "Léa", "Priya", "Daniel", "Hélène", "Mathieu",
            "Fatima", "André", "Camille", "Nathan", "Élodie", "Gabriel", "Jasmine", "Thomas", "Renée", "William",
            "Anaïs", "Samuel", "Isabelle", "Kwame", "Geneviève", "Ravi", "Maëlle", "Benoît", "Yuki", "François"
        ];

        private static readonly string[] LastNames =
        [
            "Tremblay", "Roy", "Côté", "Smith", "Nguyen", "Lévesque", "Singh", "Brown", "Gagné", "Wilson",
            "Bouchard", "Martin", "Pelletier", "Lavoie", "Fortin", "Bélanger", "Bergeron", "Leblanc", "Paquette", "Girard",
            "Simard", "Boucher", "Caron", "Beaulieu", "Cloutier", "Dubé", "Poirier", "Fournier", "Lapointe", "Leclerc",
            "Lefebvre", "Chen", "Patel", "Anderson", "Campbell", "MacDonald", "Okafor", "Hernández", "Kowalski", "St-Pierre"
        ];

        private static readonly (string En, string Fr)[] Titles =
        [
            ("Analyst", "Analyste"),
            ("Senior Analyst", "Analyste principal"),
            ("Policy Advisor", "Conseiller en politiques"),
            ("Program Officer", "Agent de programme"),
            ("Project Manager", "Gestionnaire de projet"),
            ("Director", "Directeur"),
            ("Developer", "Développeur"),
            ("Administrative Assistant", "Adjoint administratif"),
            ("Financial Officer", "Agent financier"),
            ("Communications Advisor", "Conseiller en communications")
        ];

        private static readonly (string En, string Fr)[] Branches =
        [
            ("Corporate Services", "Services ministériels"),
            ("Digital Services", "Services numériques"),
            ("Human Resources", "Ressources humaines"),
            ("Finance", "Finances"),
            ("Policy", "Politiques"),
            ("Communications", "Communications"),
            ("Operations", "Opérations"),
            ("Audit and Evaluation", "Audit et évaluation")
        ];

        private readonly AutocompleteSamplePerson[] _people;
        private readonly Dictionary<string, AutocompleteSamplePerson> _byId;

        /// <summary>
        /// Initializes a new instance of the <see cref="AutocompleteSampleDirectory"/> class with the default size and seed.
        /// </summary>
        public AutocompleteSampleDirectory()
            : this(DefaultCount, DefaultSeed)
        {
        }

        /// <summary>
        /// Initializes a new instance of the <see cref="AutocompleteSampleDirectory"/> class.
        /// </summary>
        /// <param name="count">The number of records to generate.</param>
        /// <param name="seed">The seed of the random generator.</param>
        public AutocompleteSampleDirectory(int count, int seed)
        {
            ArgumentOutOfRangeException.ThrowIfNegative(count);

#pragma warning disable CA5394 // Sample data only: a seeded, repeatable sequence is the point, not unpredictability.
            var random = new Random(seed);
            var people = new AutocompleteSamplePerson[count];

            for (int index = 0; index < count; index++)
            {
                string first = FirstNames[random.Next(FirstNames.Length)];
                string last = LastNames[random.Next(LastNames.Length)];
                var title = Titles[random.Next(Titles.Length)];
                var branch = Branches[random.Next(Branches.Length)];

                people[index] = new AutocompleteSamplePerson(
                    $"E{index + 1:D6}",
                    $"{first} {last}",
                    NormalizeTerm($"{first} {last} {last}, {first}"),
                    $"{title.En}, {branch.En}",
                    $"{title.Fr}, {branch.Fr}");
            }
#pragma warning restore CA5394

            // Ordered by the search key with a binary comparison: any database can reproduce this order exactly.
            _people = [.. people.OrderBy(person => person.SearchName, StringComparer.Ordinal).ThenBy(person => person.Id, StringComparer.Ordinal)];
            _byId = _people.ToDictionary(person => person.Id, StringComparer.Ordinal);
        }

        /// <inheritdoc/>
        public int Count => _people.Length;

        /// <inheritdoc/>
        public FDCPAutocompleteResult Search(string? term, int skip, int take, string? lang)
        {
            string folded = NormalizeTerm(term);

            if (folded.Length < MinTermLength || folded.Length > MaxTermLength)
            {
                return new FDCPAutocompleteResult(0, []);
            }

            int safeTake = Math.Clamp(take, 1, MaxPageSize);
            int safeSkip = Math.Clamp(skip, 0, MaxSkip);
            bool french = IsFrench(lang);
            var items = new List<FDCPAutocompleteItem>(safeTake);
            int total = 0;

            foreach (var person in _people)
            {
                if (!person.SearchName.Contains(folded, StringComparison.Ordinal))
                {
                    continue;
                }

                if (total >= safeSkip && items.Count < safeTake)
                {
                    items.Add(ToItem(person, french));
                }

                total++;
            }

            return new FDCPAutocompleteResult(total, items);
        }

        /// <inheritdoc/>
        public FDCPAutocompleteItem? Find(string? value, string? lang)
        {
            return value != null && _byId.TryGetValue(value, out var person) ? ToItem(person, IsFrench(lang)) : null;
        }

        /// <inheritdoc/>
        public IQueryable<AutocompleteSamplePerson> Query()
        {
            return _people.AsQueryable();
        }

        /// <summary>
        /// Tells whether a language code asks for French.
        /// </summary>
        /// <param name="lang">A language code such as <c>fr</c> or <c>fr-CA</c>.</param>
        /// <returns><c>true</c> for French; otherwise <c>false</c>.</returns>
        public static bool IsFrench(string? lang)
        {
            return lang != null && lang.StartsWith("fr", StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        /// Prepares text for searching: lower-cases, trims, collapses whitespace and strips accents, so "cote" matches "Côté".
        /// Letters that are not an accented form of another letter are spelled out: "coeur" matches "Cœur", "strasse" matches "Straße".
        /// Returns an empty string for blank text and for text that is not valid Unicode.
        /// </summary>
        /// <param name="value">The text typed by the user.</param>
        /// <returns>The normalized text.</returns>
        public static string NormalizeTerm(string? value)
        {
            if (string.IsNullOrWhiteSpace(value))
            {
                return string.Empty;
            }

            string decomposed;

            try
            {
                decomposed = value.Trim().Normalize(NormalizationForm.FormD);
            }
            catch (ArgumentException)
            {
                // Malformed Unicode (for example an unpaired surrogate) cannot match a name: treat it as no term.
                return string.Empty;
            }

            var sb = new StringBuilder(decomposed.Length);
            bool pendingSpace = false;

            foreach (char character in decomposed)
            {
                if (CharUnicodeInfo.GetUnicodeCategory(character) == UnicodeCategory.NonSpacingMark)
                {
                    continue;
                }

                if (char.IsWhiteSpace(character))
                {
                    pendingSpace = true;
                    continue;
                }

                if (pendingSpace)
                {
                    sb.Append(' ');
                    pendingSpace = false;
                }

                char lower = char.ToLowerInvariant(character);

                // These have no Unicode decomposition, so stripping accents leaves them unchanged.
                switch (lower)
                {
                    case 'œ': sb.Append("oe"); break;
                    case 'æ': sb.Append("ae"); break;
                    case 'ø': sb.Append('o'); break;
                    case 'ß': sb.Append("ss"); break;
                    case 'ł': sb.Append('l'); break;
                    default: sb.Append(lower); break;
                }
            }

            return sb.ToString();
        }

        private static FDCPAutocompleteItem ToItem(AutocompleteSamplePerson person, bool french)
        {
            return new FDCPAutocompleteItem(person.Id, person.Name, french ? person.DescriptionFr : person.DescriptionEn);
        }
    }
}
