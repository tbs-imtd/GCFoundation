namespace GCFoundation.Components.Enums
{
    /// <summary>
    /// Specifies where the "expand all" / "collapse all" toggle button is displayed relative to the accordion's sections.
    /// </summary>
    public enum AccordionButtonsPosition
    {
        /// <summary>
        /// Displays the toggle button both above and below the accordion's sections.
        /// </summary>
        both,

        /// <summary>
        /// Displays the toggle button below the accordion's sections.
        /// </summary>
        bottom,

        /// <summary>
        /// Displays the toggle button above the accordion's sections.
        /// </summary>
        top
    }
}
