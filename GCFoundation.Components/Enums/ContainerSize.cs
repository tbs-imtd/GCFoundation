namespace GCFoundation.Components.Enums
{
    /// <summary>
    /// Defines the maximum width options for alert content.
    /// </summary>
    public enum ContainerSize
    {
        /// <summary>
        /// Uses the full available width.
        /// </summary>
        full,

        /// <summary>
        /// Uses the large container width.
        /// </summary>
        lg,

        /// <summary>
        /// Uses the medium container width.
        /// </summary>
        md,

        /// <summary>
        /// Uses the small container width.
        /// </summary>
        sm,

        /// <summary>
        /// Uses the extra-large container width.
        /// </summary>
        xl,

        /// <summary>
        /// Uses the extra-small container width.
        /// </summary>
        xs
    }
}
