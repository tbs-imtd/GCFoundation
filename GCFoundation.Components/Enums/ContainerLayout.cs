namespace GCFoundation.Components.Enums
{
    /// <summary>
    /// Defines the layout options for the GCDS <c>gcds-container</c> <c>layout</c> attribute.
    /// </summary>
    public enum ContainerLayout
    {
        /// <summary>
        /// The container spans the full width of its parent.
        /// </summary>
        full,

        /// <summary>
        /// The container uses the page layout width shared with the header and footer.
        /// </summary>
        page
    }
}
